import fs from 'fs';
import path from 'path';

// This script injects environment variables provided by the Cloudflare Pages build environment
// directly into wrangler.jsonc right before deployment. This allows you to set variables securely
// in the Cloudflare Dashboard without ever hardcoding them in GitHub!

const wranglerPath = path.resolve(process.cwd(), 'wrangler.jsonc');

if (fs.existsSync(wranglerPath)) {
  const content = fs.readFileSync(wranglerPath, 'utf-8');
  let config;
  try {
    // Parse the JSONC (ignoring comments if any exist, though JSON.parse doesn't support them natively, 
    // wrangler.jsonc generated by OpenNext is usually strict JSON)
    config = JSON.parse(content);
  } catch (e) {
    console.error("❌ Failed to parse wrangler.jsonc. Ensure it is valid JSON without comments.");
    process.exit(1);
  }
  
  if (!config.vars) config.vars = {};
  
  let injected = false;
  
  // Inject variables from the build environment (e.g., Cloudflare Dashboard)
  if (process.env.GO_API_URL) {
    config.vars.GO_API_URL = process.env.GO_API_URL;
    injected = true;
  }
  
  if (process.env.AUTH_JWT_SECRET) {
    config.vars.AUTH_JWT_SECRET = process.env.AUTH_JWT_SECRET;
    injected = true;
  }
  
  if (injected) {
    fs.writeFileSync(wranglerPath, JSON.stringify(config, null, 2));
    console.log('✅ Successfully injected dynamic environment variables into wrangler.jsonc for Cloudflare deployment.');
  } else {
    console.log('⚠️ No matching environment variables found in the build environment to inject.');
  }
} else {
  console.log('⚠️ wrangler.jsonc not found. Skipping variable injection.');
}
